const supportedLanguages = ['sv', 'en', 'fr', 'ar'];

/**
 * Get a translation by language, key, and namespace
 */
export function t(lang: string, key: string, namespace: string = 'common'): string {
  const ns = translations[lang]?.[namespace];
  if (!ns) {
    // Fallback to Swedish
    const fallback = translations['sv']?.[namespace];
    return fallback?.[key] || key;
  }
  return ns[key] || translations['sv']?.[namespace]?.[key] || key;
}

/**
 * Get current language from localStorage or browser
 */
export function getCurrentLanguage(): string {
  if (typeof window !== 'undefined') {
    const saved = localStorage.getItem('i18nextLng');
    if (saved && supportedLanguages.includes(saved)) {
      return saved;
    }
    try {
      const browserLang = navigator.language.split('-')[0];
      if (supportedLanguages.includes(browserLang)) {
        return browserLang;
      }
    } catch {
      // ignore
    }
  }
  return 'sv';
}

/**
 * Set the current language
 */
export function setLanguage(lang: string): void {
  if (typeof window !== 'undefined') {
    localStorage.setItem('i18nextLng', lang);
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  }
}

